function normalizeTitle(title = '') {
  return title.toLocaleLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
}

export function getBookPreviewContent(book) {
  const title = normalizeTitle(book.title)
  return bookPreviewContent.find(({ match }) => match.some((candidate) => normalizeTitle(candidate) === title)) ?? null
}
